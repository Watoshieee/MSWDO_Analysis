        $this->applyTitleStyle($sheet, 'A1:C1', self::COLOR_PRIMARY, true);
        $sheet->getRowDimension(1)->setRowHeight(36);

        $sheet->mergeCells('A2:C2');
        $sheet->setCellValue('A2', 'Municipal Social Welfare and Development Office');
        $sheet->getStyle('A2:C2')->getFont()->setSize(10)->setItalic(true)->setColor((new Color())->setRGB(self::COLOR_MID_TEXT));
        $sheet->getStyle('A2:C2')->getAlignment()->setHorizontal(Alignment::HORIZONTAL_CENTER);
        $sheet->getRowDimension(2)->setRowHeight(18);
        $sheet->mergeCells('A3:C3');
        $sheet->getRowDimension(3)->setRowHeight(8);

        $infoRow = 4;
        foreach ([
            ['Report Title',       'MSWDO Comparative Socio-Economic Data Export'],
            ['Export Date & Time', now()->format('F j, Y \a\t g:i A')],
            ['Municipality',       $m ?: 'All Municipalities'],
            ['Year',               $y ? (string)$y : 'All Years'],
            ['Category Filter',    ucfirst($filters['category'] ?? 'all')],
        ] as $item) {

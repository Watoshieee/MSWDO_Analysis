    private function applyTitleStyle(Worksheet $sheet, string $range, string $bgColor, bool $center = true): void
    {
        $sheet->getStyle($range)->applyFromArray([
            'font'      => ['bold' => true, 'size' => self::FONT_TITLE, 'color' => ['rgb' => self::COLOR_WHITE]],
            'fill'      => ['fillType' => Fill::FILL_SOLID, 'startColor' => ['rgb' => $bgColor]],

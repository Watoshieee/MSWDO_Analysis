            $sheet->setCellValue('B'.$infoRow, $item[1]);
            $sheet->mergeCells('B'.$infoRow.':C'.$infoRow);
            $sheet->getStyle('A'.$infoRow)->getFont()->setBold(true)->setSize(self::FONT_BODY)->setColor((new Color())->setRGB(self::COLOR_PRIMARY));
            $sheet->getStyle('B'.$infoRow)->getFont()->setSize(self::FONT_BODY)->setColor((new Color())->setRGB(self::COLOR_DARK_TEXT));
            $sheet->getRowDimension($infoRow)->setRowHeight(16);
            $infoRow++;
        }
        $infoRow++;

        // Workbook contents index
        $this->writeSummarySection($sheet, $infoRow, 'WORKBOOK CONTENTS');
        $infoRow++;
        foreach ([
            ['Sheet 1', 'Municipality Yearly Data',  'Population, households, age groups per municipality/year'],
            ['Sheet 2', 'Municipality Charts',        '3 charts: Total Population, Male vs Female, Households'],
            ['Sheet 3', 'Barangay Data',              'PWD, AICS, Solo Parent, 4Ps, Senior per barangay'],
            ['Sheet 4', 'Barangay Charts',            '2 charts: Population bar, Welfare indicators column'],
            ['Sheet 5', 'Social Programs',            'Beneficiary counts per program type'],
            ['Sheet 6', 'Programs Charts',            'Column chart + Pie chart of beneficiary distribution'],
            ['Sheet 7', 'Export Summary',             'This sheet — metadata and record statistics'],
        ] as $idx => $si) {
            $sheet->setCellValue('A'.$infoRow, $si[0]);
            $sheet->setCellValue('B'.$infoRow, $si[1]);
            $sheet->setCellValue('C'.$infoRow, $si[2]);
            $sheet->getStyle('A'.$infoRow)->getFont()->setBold(true)->setSize(self::FONT_BODY)->setColor((new Color())->setRGB(self::COLOR_PRIMARY));
            $sheet->getStyle('B'.$infoRow)->getFont()->setSize(self::FONT_BODY);
            $sheet->getStyle('C'.$infoRow)->getFont()->setSize(8)->setColor((new Color())->setRGB(self::COLOR_MID_TEXT));
            if ($idx % 2 === 1) {
                $sheet->getStyle("A{$infoRow}:C{$infoRow}")->getFill()->setFillType(Fill::FILL_SOLID)->getStartColor()->setRGB(self::COLOR_ALT_ROW);
            }
            $sheet->getRowDimension($infoRow)->setRowHeight(15);
            $infoRow++;
        }
        $infoRow++;

        // Record stats
        $this->writeSummarySection($sheet, $infoRow, 'EXPORT STATISTICS');
        $infoRow++;
        foreach ([
            ['Municipality Yearly Records', $muniRecords->count()],
            ['Barangay Records',            $brgyRecords->count()],
            ['Social Program Records',      $progRecords->count()],
            ['Total Records',               $muniRecords->count() + $brgyRecords->count() + $progRecords->count()],
        ] as $i => $s) {
            $sheet->setCellValue('A'.$infoRow, $s[0]);
            $sheet->setCellValue('B'.$infoRow, $s[1]);
            $sheet->mergeCells('B'.$infoRow.':C'.$infoRow);
            $sheet->getStyle('B'.$infoRow)->getFont()->setBold(true)->setSize(self::FONT_BODY);
            $sheet->getStyle('B'.$infoRow)->getNumberFormat()->setFormatCode(NumberFormat::FORMAT_NUMBER_COMMA_SEPARATED1);
            if ($i % 2 === 1) {
                $sheet->getStyle("A{$infoRow}:C{$infoRow}")->getFill()->setFillType(Fill::FILL_SOLID)->getStartColor()->setRGB(self::COLOR_ALT_ROW);
            }
            $sheet->getRowDimension($infoRow)->setRowHeight(16);
            $infoRow++;
        }

        if ($muniRecords->isNotEmpty()) {
            $infoRow++;
            $this->writeSummarySection($sheet, $infoRow, 'DEMOGRAPHIC TOTALS');
            $infoRow++;
            foreach ([
                ['Total Population (sum)',  $muniRecords->sum('total_population')],
                ['Total Households (sum)',   $muniRecords->sum('total_households')],
                ['Total Male (sum)',         $muniRecords->sum('male_population')],
                ['Total Female (sum)',       $muniRecords->sum('female_population')],
            ] as $i => $t) {
                $sheet->setCellValue('A'.$infoRow, $t[0]);
                $sheet->setCellValue('B'.$infoRow, $t[1]);
                $sheet->mergeCells('B'.$infoRow.':C'.$infoRow);
                $sheet->getStyle('B'.$infoRow)->getNumberFormat()->setFormatCode(NumberFormat::FORMAT_NUMBER_COMMA_SEPARATED1);
                if ($i % 2 === 1) {
                    $sheet->getStyle("A{$infoRow}:C{$infoRow}")->getFill()->setFillType(Fill::FILL_SOLID)->getStartColor()->setRGB(self::COLOR_ALT_ROW);
                }
                $sheet->getRowDimension($infoRow)->setRowHeight(16);
                $infoRow++;
            }
        }

        if ($progRecords->isNotEmpty()) {
            $infoRow++;
            $sheet->setCellValue('A'.$infoRow, 'Total Social Program Beneficiaries:');
            $sheet->setCellValue('B'.$infoRow, $progRecords->sum('beneficiary_count'));
            $sheet->mergeCells('B'.$infoRow.':C'.$infoRow);
            $sheet->getStyle('A'.$infoRow)->getFont()->setBold(true)->setSize(self::FONT_BODY);
            $sheet->getStyle('B'.$infoRow)->getFont()->setBold(true)->setSize(self::FONT_BODY);
            $sheet->getStyle('B'.$infoRow)->getNumberFormat()->setFormatCode(NumberFormat::FORMAT_NUMBER_COMMA_SEPARATED1);
            $sheet->getRowDimension($infoRow)->setRowHeight(16);
            $infoRow++;
        }

        $infoRow++;
        $sheet->mergeCells("A{$infoRow}:C{$infoRow}");
        $sheet->setCellValue("A{$infoRow}", 'DISCLAIMER');
        $sheet->getStyle("A{$infoRow}:C{$infoRow}")->getFont()->setBold(true)->setSize(9)->setColor((new Color())->setRGB(self::COLOR_RED));
        $infoRow++;
        $sheet->mergeCells("A{$infoRow}:C{$infoRow}");
        $sheet->setCellValue("A{$infoRow}", 'This report was generated by the MSWDO Analysis System. Data is based on official records and should be used for reference purposes only.');
        $sheet->getStyle("A{$infoRow}:C{$infoRow}")->getFont()->setSize(8)->setItalic(true);
        $sheet->getStyle("A{$infoRow}:C{$infoRow}")->getAlignment()->setWrapText(true)->setVertical(Alignment::VERTICAL_TOP);
        $sheet->getRowDimension($infoRow)->setRowHeight(40);

        $sheet->getColumnDimension('A')->setWidth(42);
        $sheet->getColumnDimension('B')->setWidth(32);
        $sheet->getColumnDimension('C')->setWidth(28);

        $sheet->getPageSetup()
            ->setOrientation(\PhpOffice\PhpSpreadsheet\Worksheet\PageSetup::ORIENTATION_PORTRAIT)
            ->setPaperSize(\PhpOffice\PhpSpreadsheet\Worksheet\PageSetup::PAPERSIZE_A4)
            ->setFitToWidth(1)->setFitToHeight(0)->setHorizontalCentered(true);
        $sheet->getPageMargins()->setTop(0.75)->setBottom(0.75)->setLeft(0.75)->setRight(0.75);
        $sheet->getHeaderFooter()
            ->setOddHeader('&C&"Arial,Bold"&12MSWDO Data Export Summary')
            ->setOddFooter('&L'.now()->format('Y-m-d').'&CPage &P of &N&RConfidential');
    }


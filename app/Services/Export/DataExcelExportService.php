    }

    private function writeHeaders(Worksheet $sheet, int $row, array $headers, string $bgColor): void
    {
        foreach ($headers as $colIdx => $header) {
            $col = Coordinate::stringFromColumnIndex($colIdx + 1);
            $sheet->setCellValue("{$col}{$row}", $header);
        }
        $lastCol = Coordinate::stringFromColumnIndex(count($headers));
        $sheet->getStyle("A{$row}:{$lastCol}{$row}")->applyFromArray([
            'font'      => ['bold' => true, 'size' => self::FONT_HEADER, 'color' => ['rgb' => self::COLOR_WHITE]],
            'fill'      => ['fillType' => Fill::FILL_SOLID, 'startColor' => ['rgb' => $bgColor]],
            'alignment' => ['horizontal' => Alignment::HORIZONTAL_CENTER, 'vertical' => Alignment::VERTICAL_CENTER, 'wrapText' => true],
            'borders'   => ['allBorders' => ['borderStyle' => Border::BORDER_THIN, 'color' => ['rgb' => 'AAAAAA']]],
        ]);
        $sheet->getRowDimension($row)->setRowHeight(22);
        $sheet->freezePane("A".($row + 1));
        $sheet->setAutoFilter("A{$row}:{$lastCol}{$row}");
    }

    private function writeDataRow(Worksheet $sheet, int $row, array $data, bool $alternate): void
    {
        foreach ($data as $colIdx => $value) {
            $col = Coordinate::stringFromColumnIndex($colIdx + 1);
            $sheet->setCellValue("{$col}{$row}", $value);
        }
        $lastCol   = Coordinate::stringFromColumnIndex(count($data));
        $fillColor = $alternate ? self::COLOR_ALT_ROW : self::COLOR_WHITE;
        $sheet->getStyle("A{$row}:{$lastCol}{$row}")->applyFromArray([
            'font'      => ['size' => self::FONT_BODY],
            'fill'      => ['fillType' => Fill::FILL_SOLID, 'startColor' => ['rgb' => $fillColor]],
            'alignment' => ['vertical' => Alignment::VERTICAL_CENTER],
            'borders'   => ['allBorders' => ['borderStyle' => Border::BORDER_THIN, 'color' => ['rgb' => self::COLOR_BORDER]]],
        ]);
        for ($i = 1; $i <= count($data); $i++) {
            $col   = Coordinate::stringFromColumnIndex($i);
            $align = is_numeric($data[$i - 1]) ? Alignment::HORIZONTAL_RIGHT : Alignment::HORIZONTAL_LEFT;
            $sheet->getStyle("{$col}{$row}")->getAlignment()->setHorizontal($align);
        }
        $sheet->getRowDimension($row)->setRowHeight(15);
    }


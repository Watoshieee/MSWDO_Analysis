/**
 * DataExcelExportService
 *
 * 7-sheet workbook:
 *  Sheet 1 – Municipality Yearly Data  (table)
 *  Sheet 2 – Municipality Charts        (3 charts)
 *  Sheet 3 – Barangay Data             (table)
 *  Sheet 4 – Barangay Charts           (2 charts)
 *  Sheet 5 – Social Programs           (table)
 *  Sheet 6 – Programs Charts           (column + pie)
 *  Sheet 7 – Export Summary
 */
class DataExcelExportService
{
    // ── MSWDO Brand Colors ────────────────────────────────────────
    const COLOR_PRIMARY   = '2C3E8F';
    const COLOR_SECONDARY = 'FDB913';
    const COLOR_RED       = 'C41E24';
    const COLOR_WHITE     = 'FFFFFF';
    const COLOR_BORDER    = 'CBD5E1';
    const COLOR_ALT_ROW   = 'EEF2FF';
    const COLOR_DARK_TEXT = '1E293B';
    const COLOR_MID_TEXT  = '475569';

    const FONT_TITLE  = 14;
    const FONT_HEADER = 10;
    const FONT_BODY   = 9;

    // Distinct colors for multi-series / pie slices
    const PALETTE = [
        '2C3E8F', 'FDB913', 'C41E24', '16A34A', '7C3AED',
        'EA580C', '0891B2', 'BE185D', '65A30D', '9333EA',
    ];

    // ══════════════════════════════════════════════════════════════
    //  PUBLIC: generate workbook
    // ══════════════════════════════════════════════════════════════

    public function generateWorkbook(array $filters = []): string
    {
        $municipality = $filters['municipality'] ?? null;
        $year = isset($filters['year']) && $filters['year'] !== 'all' && $filters['year'] !== ''
            ? (int) $filters['year'] : null;

        $muniRecords = $this->fetchMunicipalityData($municipality, $year);
        $brgyRecords = $this->fetchBarangayData($municipality, $year);
        $progRecords = $this->fetchProgramData($municipality, $year);

        $spreadsheet = new Spreadsheet();
        $spreadsheet->getProperties()
            ->setCreator('MSWDO Analysis System')
            ->setTitle('MSWDO Data Export')
            ->setSubject('Municipal Social Welfare Data')
            ->setDescription('Generated by MSWDO Analysis System.');

        // Sheet 1 – Municipality data table
        $shMuni = $spreadsheet->getActiveSheet()->setTitle('Municipality Yearly Data');
        $this->buildMunicipalitySheet($shMuni, $muniRecords, $municipality, $year);

        // Sheet 2 – Municipality charts
        $shMuniC = $spreadsheet->createSheet()->setTitle('Municipality Charts');
        $this->buildMunicipalityCharts($shMuniC, $muniRecords);

        // Sheet 3 – Barangay data table
        $shBrgy = $spreadsheet->createSheet()->setTitle('Barangay Data');
        $this->buildBarangaySheet($shBrgy, $brgyRecords, $municipality, $year);

        // Sheet 4 – Barangay charts
        $shBrgyC = $spreadsheet->createSheet()->setTitle('Barangay Charts');
        $this->buildBarangayCharts($shBrgyC, $brgyRecords);

        // Sheet 5 – Social Programs data table
        $shProg = $spreadsheet->createSheet()->setTitle('Social Programs');
        $this->buildProgramsSheet($shProg, $progRecords, $municipality, $year);

        // Sheet 6 – Programs charts
        $shProgC = $spreadsheet->createSheet()->setTitle('Programs Charts');
        $this->buildProgramsCharts($shProgC, $progRecords);

        // Sheet 7 – Summary
        $shSumm = $spreadsheet->createSheet()->setTitle('Export Summary');
        $this->buildSummarySheet($shSumm, $muniRecords, $brgyRecords, $progRecords, $municipality, $year, $filters);

        $spreadsheet->setActiveSheetIndex(0);

        $tempDir = storage_path('app/temp/data_exports');
        if (!is_dir($tempDir)) {
            mkdir($tempDir, 0755, true);
        }
        $filePath = $tempDir . DIRECTORY_SEPARATOR . uniqid('data_export_', true) . '.xlsx';
        $writer   = new Xlsx($spreadsheet);
        $writer->setIncludeCharts(true);
        $writer->save($filePath);

        return $filePath;
    }

    // ══════════════════════════════════════════════════════════════
    //  DATA FETCHERS
    // ══════════════════════════════════════════════════════════════

    private function fetchMunicipalityData(?string $m, ?int $y): \Illuminate\Support\Collection
    {
        $q = MunicipalityYearlySummary::query()->orderBy('municipality')->orderBy('year', 'desc');
        if ($m) $q->where('municipality', $m);
        if ($y) $q->where('year', $y);
        return $q->get();
    }

    private function fetchBarangayData(?string $m, ?int $y): \Illuminate\Support\Collection
    {
        $q = Barangay::query()->orderBy('municipality')->orderBy('name')->orderBy('year', 'desc');
        if ($m) $q->where('municipality', $m);
        if ($y) $q->where('year', $y);
        return $q->get();
    }

    private function fetchProgramData(?string $m, ?int $y): \Illuminate\Support\Collection
    {
        $q = SocialWelfareProgram::query()->orderBy('municipality')->orderBy('year', 'desc')->orderBy('program_type');
        if ($m) $q->where('municipality', $m);
        if ($y) $q->where('year', $y);
        return $q->get();
    }

    // ══════════════════════════════════════════════════════════════
    //  DATA TABLE SHEETS
    // ══════════════════════════════════════════════════════════════

    private function buildMunicipalitySheet(Worksheet $sheet, $records, ?string $m, ?int $y): void
    {
        $headers = ['Year','Municipality','Total Population','Male','Female','Age 0–19','Age 20–59','Age 60+','Households'];
        $this->writeSheetTitle($sheet, 'Municipality Yearly Data', $this->buildSubtitle($m, $y), count($headers));
        $hRow = 4;
        $this->writeHeaders($sheet, $hRow, $headers, self::COLOR_PRIMARY);
        $row = $hRow + 1;
        foreach ($records as $i => $r) {
            $this->writeDataRow($sheet, $row, [
                $r->year, $r->municipality,
                (int)($r->total_population ?? 0), (int)($r->male_population ?? 0),
                (int)($r->female_population ?? 0), (int)($r->population_0_19 ?? 0),
                (int)($r->population_20_59 ?? 0), (int)($r->population_60_100 ?? 0),
                (int)($r->total_households ?? 0),
            ], $i % 2 === 0);
            foreach (['C','D','E','F','G','H','I'] as $c) {
                $sheet->getCell($c.$row)->getStyle()->getNumberFormat()->setFormatCode(NumberFormat::FORMAT_NUMBER_COMMA_SEPARATED1);
            }
            $row++;
        }
        if ($records->isEmpty()) {
            $this->writeEmptyState($sheet, $hRow + 1, count($headers), 'No municipality yearly data available.');
        }
        $this->applySheetLayout($sheet, count($headers), $row - 1, $hRow,
            ['A'=>8,'B'=>22,'C'=>18,'D'=>12,'E'=>12,'F'=>12,'G'=>12,'H'=>12,'I'=>14], 'landscape');
    }

    private function buildBarangaySheet(Worksheet $sheet, $records, ?string $m, ?int $y): void
    {
        $headers = ['Year','Municipality','Barangay','Total Population','PWD','AICS','Solo Parent','Households','4Ps','Senior'];
        $this->writeSheetTitle($sheet, 'Barangay Data', $this->buildSubtitle($m, $y), count($headers));
        $hRow = 4;
        $this->writeHeaders($sheet, $hRow, $headers, self::COLOR_PRIMARY);
        $row = $hRow + 1;
        foreach ($records as $i => $b) {
            $this->writeDataRow($sheet, $row, [
                $b->year ?? '', $b->municipality, $b->name,
                (int)($b->total_population ?? 0), (int)($b->pwd_count ?? 0),
                (int)($b->aics_count ?? 0), (int)($b->single_parent_count ?? 0),
                (int)($b->total_households ?? 0), (int)($b->four_ps_count ?? 0),
                (int)($b->senior_count ?? 0),
            ], $i % 2 === 0);
            foreach (['D','E','F','G','H','I','J'] as $c) {
                $sheet->getCell($c.$row)->getStyle()->getNumberFormat()->setFormatCode(NumberFormat::FORMAT_NUMBER_COMMA_SEPARATED1);
            }
            $row++;
        }
        if ($records->isEmpty()) {
            $this->writeEmptyState($sheet, $hRow + 1, count($headers), 'No barangay data available.');
        }
        $this->applySheetLayout($sheet, count($headers), $row - 1, $hRow,
            ['A'=>8,'B'=>22,'C'=>24,'D'=>16,'E'=>10,'F'=>10,'G'=>14,'H'=>14,'I'=>10,'J'=>10], 'landscape');
    }

    private function buildProgramsSheet(Worksheet $sheet, $records, ?string $m, ?int $y): void
    {
        // Use PRIMARY blue for header — NOT red
        $headers = ['Year','Municipality','Program Type','Beneficiary Count'];
        $this->writeSheetTitle($sheet, 'Social Programs', $this->buildSubtitle($m, $y), count($headers));
        $hRow = 4;
        $this->writeHeaders($sheet, $hRow, $headers, self::COLOR_PRIMARY);
        $row = $hRow + 1;
        foreach ($records as $i => $p) {
            $this->writeDataRow($sheet, $row, [
                $p->year, $p->municipality,
                str_replace('_', ' ', $p->program_type),
                (int)($p->beneficiary_count ?? 0),
            ], $i % 2 === 0);
            $sheet->getCell('D'.$row)->getStyle()->getNumberFormat()->setFormatCode(NumberFormat::FORMAT_NUMBER_COMMA_SEPARATED1);
            $row++;
        }
        if ($records->isEmpty()) {
            $this->writeEmptyState($sheet, $hRow + 1, count($headers), 'No social program data available.');
        }
        $this->applySheetLayout($sheet, count($headers), $row - 1, $hRow,
            ['A'=>8,'B'=>24,'C'=>28,'D'=>18], 'portrait');
    }

    // ══════════════════════════════════════════════════════════════
    //  CHART SHEETS
    // Charts use in-memory arrays (no cell-reference issues).
    // Data is also written to a visible helper table on the sheet
    // so users can see the exact numbers behind each chart.
    // ══════════════════════════════════════════════════════════════

    /** Sheet 2 — Municipality Charts */
    private function buildMunicipalityCharts(Worksheet $sheet, $records): void
    {
        $this->writeChartSheetTitle($sheet, 'Municipality Yearly Data — Charts');

        if ($records->isEmpty()) {
            $sheet->setCellValue('A4', 'No data available to chart. Please add municipality yearly data first.');
            $sheet->getStyle('A4')->getFont()->setItalic(true)->setSize(10)->setColor((new Color())->setRGB(self::COLOR_MID_TEXT));
            return;
        }

        // Aggregate: latest year per municipality
        $byMuni  = $records->groupBy('municipality')->map(fn($rows) => $rows->sortByDesc('year')->first());
        $labels  = $byMuni->keys()->values()->toArray();
        $pop     = $byMuni->map(fn($r) => (int)($r->total_population   ?? 0))->values()->toArray();
        $male    = $byMuni->map(fn($r) => (int)($r->male_population    ?? 0))->values()->toArray();
        $female  = $byMuni->map(fn($r) => (int)($r->female_population  ?? 0))->values()->toArray();
        $hh      = $byMuni->map(fn($r) => (int)($r->total_households   ?? 0))->values()->toArray();
        $n       = count($labels);

        // ── Write visible data table ──────────────────────────────
        $tRow = 4;
        $this->writeChartDataTable($sheet, $tRow, 'A',
            ['Municipality', 'Total Population', 'Male', 'Female', 'Households'],
            array_map(null, $labels, $pop, $male, $female, $hh)
        );

        // Chart start row (below table + gap)
        $chartTop = $tRow + $n + 3;

        // ── Chart 1: Total Population ─────────────────────────────
        $c1 = $this->makeColumnChartFromArrays(
            'ch_muni_pop', 'Total Population by Municipality',
            $labels,
            [['label' => 'Total Population', 'data' => $pop, 'color' => self::PALETTE[0]]]
        );
        $c1->setTopLeftPosition($this->rowToCell('A', $chartTop));
        $c1->setBottomRightPosition($this->rowToCell('I', $chartTop + 20));
        $sheet->addChart($c1);

        // ── Chart 2: Male vs Female ───────────────────────────────
        $c2 = $this->makeColumnChartFromArrays(
            'ch_muni_gender', 'Male vs Female Population',
            $labels,
            [
                ['label' => 'Male',   'data' => $male,   'color' => self::PALETTE[0]],
                ['label' => 'Female', 'data' => $female, 'color' => self::PALETTE[2]],
            ]
        );
        $c2->setTopLeftPosition($this->rowToCell('A', $chartTop + 22));
        $c2->setBottomRightPosition($this->rowToCell('I', $chartTop + 42));
        $sheet->addChart($c2);

        // ── Chart 3: Households ───────────────────────────────────
        $c3 = $this->makeColumnChartFromArrays(
            'ch_muni_hh', 'Households by Municipality',
            $labels,
            [['label' => 'Households', 'data' => $hh, 'color' => self::PALETTE[3]]]
        );
        $c3->setTopLeftPosition($this->rowToCell('A', $chartTop + 44));
        $c3->setBottomRightPosition($this->rowToCell('I', $chartTop + 64));
        $sheet->addChart($c3);

        $this->applyChartSheetLayout($sheet);
    }

    /** Sheet 4 — Barangay Charts */
    private function buildBarangayCharts(Worksheet $sheet, $records): void
    {
        $this->writeChartSheetTitle($sheet, 'Barangay Data — Charts');

        if ($records->isEmpty()) {
            $sheet->setCellValue('A4', 'No data available to chart. Please add barangay data first.');
            $sheet->getStyle('A4')->getFont()->setItalic(true)->setSize(10)->setColor((new Color())->setRGB(self::COLOR_MID_TEXT));
            return;
        }

        // Use latest year per barangay, top 15 by population
        $byBrgy  = $records->groupBy(fn($r) => $r->municipality.'|'.$r->name)
            ->map(fn($rows) => $rows->sortByDesc('year')->first())
            ->sortByDesc('total_population')
            ->take(15)->values();

        $labels = $byBrgy->map(fn($r) => substr($r->name, 0, 16))->toArray();
        $pop    = $byBrgy->map(fn($r) => (int)($r->total_population   ?? 0))->toArray();
        $pwd    = $byBrgy->map(fn($r) => (int)($r->pwd_count          ?? 0))->toArray();
        $aics   = $byBrgy->map(fn($r) => (int)($r->aics_count         ?? 0))->toArray();
        $sp     = $byBrgy->map(fn($r) => (int)($r->single_parent_count?? 0))->toArray();
        $ps     = $byBrgy->map(fn($r) => (int)($r->four_ps_count      ?? 0))->toArray();
        $senior = $byBrgy->map(fn($r) => (int)($r->senior_count       ?? 0))->toArray();
        $n      = count($labels);

        // Write visible data table
        $tRow = 4;
        $this->writeChartDataTable($sheet, $tRow, 'A',
            ['Barangay','Population','PWD','AICS','Solo Parent','4Ps','Senior'],
            array_map(null, $labels, $pop, $pwd, $aics, $sp, $ps, $senior)
        );

        $chartTop = $tRow + $n + 3;

        // Chart 1: Bar — Population per Barangay
        $c1 = $this->makeBarChartFromArrays(
            'ch_brgy_pop', 'Total Population by Barangay (Top '.$n.')',
            $labels,
            [['label' => 'Population', 'data' => $pop, 'color' => self::PALETTE[0]]]
        );
        $c1->setTopLeftPosition($this->rowToCell('A', $chartTop));
        $c1->setBottomRightPosition($this->rowToCell('I', $chartTop + 22));
        $sheet->addChart($c1);

        // Chart 2: Column — Welfare indicators
        $c2 = $this->makeColumnChartFromArrays(
            'ch_brgy_welfare', 'Welfare Indicators by Barangay',
            $labels,
            [
                ['label' => 'PWD',         'data' => $pwd,    'color' => self::PALETTE[0]],
                ['label' => 'AICS',        'data' => $aics,   'color' => self::PALETTE[1]],
                ['label' => 'Solo Parent', 'data' => $sp,     'color' => self::PALETTE[2]],
                ['label' => '4Ps',         'data' => $ps,     'color' => self::PALETTE[3]],
                ['label' => 'Senior',      'data' => $senior, 'color' => self::PALETTE[4]],
            ]
        );
        $c2->setTopLeftPosition($this->rowToCell('A', $chartTop + 24));
        $c2->setBottomRightPosition($this->rowToCell('I', $chartTop + 46));
        $sheet->addChart($c2);

        $this->applyChartSheetLayout($sheet);
    }

    /** Sheet 6 — Programs Charts */
    private function buildProgramsCharts(Worksheet $sheet, $records): void
    {
        $this->writeChartSheetTitle($sheet, 'Social Programs — Charts');

        if ($records->isEmpty()) {
            $sheet->setCellValue('A4', 'No data available to chart. Please add social program data first.');
            $sheet->getStyle('A4')->getFont()->setItalic(true)->setSize(10)->setColor((new Color())->setRGB(self::COLOR_MID_TEXT));
            return;
        }

        // Aggregate total beneficiaries per program type
        $byProg  = $records->groupBy('program_type')
            ->map(fn($rows) => $rows->sum('beneficiary_count'))
            ->sortDesc();

        $labels  = $byProg->keys()->map(fn($p) => str_replace('_', ' ', $p))->values()->toArray();
        $counts  = $byProg->values()->toArray();
        $n       = count($labels);

        // Write visible data table
        $tRow = 4;
        $this->writeChartDataTable($sheet, $tRow, 'A',
            ['Program Type', 'Total Beneficiaries'],
            array_map(null, $labels, $counts)
        );

        $chartTop = $tRow + $n + 3;

        // Chart 1: Multi-color column — Beneficiaries by Program
        $colors = array_slice(self::PALETTE, 0, $n);
        $svCol  = new DataSeriesValues(DataSeriesValues::DATASERIES_TYPE_NUMBER, null, null, $n, $counts);
        $svCol->setFillColor($colors);
        $catCol = [new DataSeriesValues(DataSeriesValues::DATASERIES_TYPE_STRING, null, null, $n, $labels)];
        $lblCol = [new DataSeriesValues(DataSeriesValues::DATASERIES_TYPE_STRING, null, null, 1, ['Beneficiaries'])];
        $dsCol  = new DataSeries(DataSeries::TYPE_BARCHART, DataSeries::GROUPING_CLUSTERED, [0], $lblCol, $catCol, [$svCol]);
        $dsCol->setPlotDirection(DataSeries::DIRECTION_COL);
        $c1 = new Chart('ch_prog_col', new Title('Beneficiaries by Program Type'),
            new Legend(Legend::POSITION_BOTTOM, new Layout(), false),
            new PlotArea(new Layout(), [$dsCol]), true, 0, null, null);
        $c1->setTopLeftPosition($this->rowToCell('A', $chartTop));
        $c1->setBottomRightPosition($this->rowToCell('I', $chartTop + 22));
        $sheet->addChart($c1);

        // Chart 2: Pie chart
        $svPie  = new DataSeriesValues(DataSeriesValues::DATASERIES_TYPE_NUMBER, null, null, $n, $counts);
        $svPie->setFillColor($colors);
        $catPie = [new DataSeriesValues(DataSeriesValues::DATASERIES_TYPE_STRING, null, null, $n, $labels)];
        $lblPie = [new DataSeriesValues(DataSeriesValues::DATASERIES_TYPE_STRING, null, null, 1, ['Programs'])];
        $dsPie  = new DataSeries(DataSeries::TYPE_PIECHART, null, [0], $lblPie, $catPie, [$svPie]);
        $pieLayout = new Layout();
        $pieLayout->setShowPercent(true);
        $pieLayout->setShowCatName(true);
        $pieLayout->setShowVal(false);
        $c2 = new Chart('ch_prog_pie', new Title('Beneficiary Distribution (%)'),
            new Legend(Legend::POSITION_RIGHT, new Layout(), false),
            new PlotArea($pieLayout, [$dsPie]), true, 0, null, null);
        $c2->setTopLeftPosition($this->rowToCell('A', $chartTop + 24));
        $c2->setBottomRightPosition($this->rowToCell('I', $chartTop + 46));
        $sheet->addChart($c2);

        $this->applyChartSheetLayout($sheet);
    }

    // ══════════════════════════════════════════════════════════════
    //  CHART FACTORY HELPERS  (array-based, no cell references)

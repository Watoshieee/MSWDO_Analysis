    /**
     * Build a clustered column chart from PHP arrays.
     * $series = [['label'=>'...', 'data'=>[...], 'color'=>'hex'], ...]
     */
    private function makeColumnChartFromArrays(string $id, string $title, array $categories, array $series): Chart
    {
        $n     = count($categories);
        $cats  = [new DataSeriesValues(DataSeriesValues::DATASERIES_TYPE_STRING, null, null, $n, $categories)];
        $lbls  = [];
        $vals  = [];
        foreach ($series as $s) {
            $lbls[] = new DataSeriesValues(DataSeriesValues::DATASERIES_TYPE_STRING, null, null, 1, [$s['label']]);
            $sv = new DataSeriesValues(DataSeriesValues::DATASERIES_TYPE_NUMBER, null, null, count($s['data']), $s['data']);
            $sv->setFillColor($s['color']);
            $vals[] = $sv;
        }
        $ds = new DataSeries(DataSeries::TYPE_BARCHART, DataSeries::GROUPING_CLUSTERED,
            range(0, count($series) - 1), $lbls, $cats, $vals);
        $ds->setPlotDirection(DataSeries::DIRECTION_COL);
        return new Chart($id, new Title($title),
            new Legend(Legend::POSITION_BOTTOM, new Layout(), false),
            new PlotArea(new Layout(), [$ds]), true, 0, null, null);
    }

    /**
     * Build a horizontal bar chart from PHP arrays.
     */
    private function makeBarChartFromArrays(string $id, string $title, array $categories, array $series): Chart
    {
        $n    = count($categories);
        $cats = [new DataSeriesValues(DataSeriesValues::DATASERIES_TYPE_STRING, null, null, $n, $categories)];
        $lbls = [];
        $vals = [];
        foreach ($series as $s) {
            $lbls[] = new DataSeriesValues(DataSeriesValues::DATASERIES_TYPE_STRING, null, null, 1, [$s['label']]);
            $sv = new DataSeriesValues(DataSeriesValues::DATASERIES_TYPE_NUMBER, null, null, count($s['data']), $s['data']);
            $sv->setFillColor($s['color']);
            $vals[] = $sv;
        }
        $ds = new DataSeries(DataSeries::TYPE_BARCHART, DataSeries::GROUPING_CLUSTERED,
            range(0, count($series) - 1), $lbls, $cats, $vals);
        $ds->setPlotDirection(DataSeries::DIRECTION_BAR);
        return new Chart($id, new Title($title),
            new Legend(Legend::POSITION_BOTTOM, new Layout(), false),
            new PlotArea(new Layout(), [$ds]), true, 0, null, null);
    }

    // ══════════════════════════════════════════════════════════════
    //  HELPER: visible data table on chart sheets
    // ══════════════════════════════════════════════════════════════

    /**
     * Write a small, styled data table onto the chart sheet so users
     * can see the numbers behind each chart.
     *
     * @param array $headers  Column headers
     * @param array $rows     Array of row arrays (values aligned to $headers)
     */
    private function writeChartDataTable(Worksheet $sheet, int $startRow, string $startCol, array $headers, array $rows): void
    {
        $colCount = count($headers);
        $startColIdx = Coordinate::columnIndexFromString($startCol);

        // Header row
        foreach ($headers as $i => $h) {
            $col = Coordinate::stringFromColumnIndex($startColIdx + $i);
            $sheet->setCellValue($col.$startRow, $h);
        }
        $endCol = Coordinate::stringFromColumnIndex($startColIdx + $colCount - 1);
        $range  = "{$startCol}{$startRow}:{$endCol}{$startRow}";
        $sheet->getStyle($range)->applyFromArray([
            'font'      => ['bold' => true, 'size' => 9, 'color' => ['rgb' => self::COLOR_WHITE]],
            'fill'      => ['fillType' => Fill::FILL_SOLID, 'startColor' => ['rgb' => self::COLOR_PRIMARY]],
            'alignment' => ['horizontal' => Alignment::HORIZONTAL_CENTER, 'vertical' => Alignment::VERTICAL_CENTER, 'wrapText' => true],
            'borders'   => ['allBorders' => ['borderStyle' => Border::BORDER_THIN, 'color' => ['rgb' => self::COLOR_BORDER]]],
        ]);
        $sheet->getRowDimension($startRow)->setRowHeight(20);

        // Set column widths
        for ($i = 0; $i < $colCount; $i++) {
            $col = Coordinate::stringFromColumnIndex($startColIdx + $i);
            $sheet->getColumnDimension($col)->setWidth($i === 0 ? 22 : 16);
        }

        // Data rows
        foreach ($rows as $rIdx => $rowData) {
            $r = $startRow + 1 + $rIdx;
            $alt = ($rIdx % 2 === 0);
            foreach ((array)$rowData as $i => $val) {
                $col = Coordinate::stringFromColumnIndex($startColIdx + $i);
                $sheet->setCellValue($col.$r, $val ?? 0);
            }
            $rowRange = "{$startCol}{$r}:{$endCol}{$r}";
            $sheet->getStyle($rowRange)->applyFromArray([
                'font'      => ['size' => 9],
                'fill'      => ['fillType' => Fill::FILL_SOLID, 'startColor' => ['rgb' => $alt ? self::COLOR_ALT_ROW : self::COLOR_WHITE]],
                'alignment' => ['vertical' => Alignment::VERTICAL_CENTER],
                'borders'   => ['allBorders' => ['borderStyle' => Border::BORDER_THIN, 'color' => ['rgb' => self::COLOR_BORDER]]],
            ]);
            // Right-align numeric columns
            for ($i = 1; $i < $colCount; $i++) {
                $col = Coordinate::stringFromColumnIndex($startColIdx + $i);
                $sheet->getStyle($col.$r)->getAlignment()->setHorizontal(Alignment::HORIZONTAL_RIGHT);
                $sheet->getStyle($col.$r)->getNumberFormat()->setFormatCode(NumberFormat::FORMAT_NUMBER_COMMA_SEPARATED1);
            }
            $sheet->getRowDimension($r)->setRowHeight(15);
        }
    }


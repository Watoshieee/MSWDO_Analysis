    }

    private function applySheetLayout(Worksheet $sheet, int $colCount, int $lastDataRow, int $headerRow, array $colWidths, string $orientation): void
    {
        foreach ($colWidths as $col => $width) {
            $sheet->getColumnDimension($col)->setWidth($width);
        }
        $lastCol = Coordinate::stringFromColumnIndex($colCount);
        $sheet->getPageSetup()->setPrintArea("A1:{$lastCol}{$lastDataRow}");
        $sheet->getPageSetup()->setRowsToRepeatAtTopByStartAndEnd($headerRow, $headerRow);
        $orientConst = $orientation === 'landscape'
            ? \PhpOffice\PhpSpreadsheet\Worksheet\PageSetup::ORIENTATION_LANDSCAPE
            : \PhpOffice\PhpSpreadsheet\Worksheet\PageSetup::ORIENTATION_PORTRAIT;
        $sheet->getPageSetup()->setOrientation($orientConst)
            ->setPaperSize(\PhpOffice\PhpSpreadsheet\Worksheet\PageSetup::PAPERSIZE_A4)
            ->setFitToWidth(1)->setFitToHeight(0)->setHorizontalCentered(true);
        $sheet->getPageMargins()->setTop(0.75)->setBottom(0.75)->setLeft(0.75)->setRight(0.75)->setHeader(0.3)->setFooter(0.3);
        $sheet->getHeaderFooter()
            ->setOddHeader('&L&"Arial,Bold"&10MSWDO Analysis System&C'.$sheet->getTitle().'&R'.now()->format('Y-m-d'))
            ->setOddFooter('&LConfidential — MSWDO&CPage &P of &N&RGenerated: '.now()->format('Y-m-d H:i'));
        $sheet->setPrintGridlines(false);
        $sheet->setShowGridlines(true);
    }

    private function rowToCell(string $col, int $row): string
    {
        return $col . $row;
    }

    private function buildSubtitle(?string $m, ?int $y): string
    {
        $parts = [];
        if ($m) $parts[] = "Municipality: {$m}";
        if ($y) $parts[] = "Year: {$y}";
        if (empty($parts)) $parts[] = 'All Municipalities · All Years';
        $parts[] = 'Generated: '.now()->format('F j, Y \a\t g:i A');
        return implode('  |  ', $parts);
    }

    public function buildFilename(?string $m, ?int $y): string
    {
        $muniSlug = $m ? strtolower(preg_replace('/[^a-zA-Z0-9_-]/', '_', $m)) : 'all_municipalities';
        $yearSlug = $y ? (string)$y : 'all_years';
        return "{$muniSlug}_{$yearSlug}_data_export.xlsx";
    }
